function BugConfig.GetAllBugs()
    local result = {}
    for _, bug in pairs(BugConfig.Bugs) do
        table.insert(result, bug)
    end
    table.sort(result, function(a, b)
        local rarityA = BugConfig.RarityOrder[a.rarity] or 0
        local rarityB = BugConfig.RarityOrder[b.rarity] or 0
        if rarityA ~= rarityB then
            return rarityA < rarityB
        end
        return a.displayName < b.displayName
    end)
    return result
end

function BugConfig.GetBugsByRarity(rarity: string)
    local result = {}
    for _, bug in pairs(BugConfig.Bugs) do
        if bug.rarity == rarity then
            table.insert(result, bug)
        end
    end
    table.sort(result, function(a, b)
        return a.displayName < b.displayName
    end)
    return result
end

function BugConfig.GetBugsWithAbilities()
    local result = {}
    for _, bug in pairs(BugConfig.Bugs) do
        if bug.ability ~= nil then
